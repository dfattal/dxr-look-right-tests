function hash3(x, y, z) {
  let h = (x * 374761393 + y * 668265263 + z * 2147483647) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967295;
}
function vnoise(x, y, z) {
  const xi = Math.floor(x), yi = Math.floor(y), zi = Math.floor(z);
  let fx = x - xi, fy = y - yi, fz = z - zi;
  fx = fx * fx * (3 - 2 * fx); fy = fy * fy * (3 - 2 * fy); fz = fz * fz * (3 - 2 * fz);
  const l = (a, b, t) => a + (b - a) * t;
  return l(
    l(l(hash3(xi, yi, zi), hash3(xi + 1, yi, zi), fx), l(hash3(xi, yi + 1, zi), hash3(xi + 1, yi + 1, zi), fx), fy),
    l(l(hash3(xi, yi, zi + 1), hash3(xi + 1, yi, zi + 1), fx), l(hash3(xi, yi + 1, zi + 1), hash3(xi + 1, yi + 1, zi + 1), fx), fy),
    fz);
}
function fbm(x, y, z, oct) {
  let s = 0, a = 0.5, n = 0;
  for (let i = 0; i < oct; i++) { s += a * vnoise(x, y, z); n += a; x *= 2.03; y *= 2.03; z *= 2.03; a *= 0.5; }
  return s / n;
}

function boxBlur(src, W, H, r) {
  const tmp = new Float32Array(W * H), out = new Float32Array(W * H);
  const k = 2 * r + 1;
  for (let y = 0; y < H; y++) {            // horizontal, wrapping in longitude
    let s = 0;
    for (let i = -r; i <= r; i++) s += src[y * W + ((i + W) % W)];
    for (let x = 0; x < W; x++) {
      tmp[y * W + x] = s / k;
      s += src[y * W + ((x + r + 1) % W)] - src[y * W + ((x - r + W) % W)];
    }
  }
  for (let x = 0; x < W; x++) {            // vertical, clamped at the poles
    let s = 0;
    for (let i = -r; i <= r; i++) s += tmp[Math.min(H - 1, Math.max(0, i)) * W + x];
    for (let y = 0; y < H; y++) {
      out[y * W + x] = s / k;
      s += tmp[Math.min(H - 1, y + r + 1) * W + x] - tmp[Math.max(0, y - r) * W + x];
    }
  }
  return out;
}

const smooth = (a, b, x) => { const t = Math.min(1, Math.max(0, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const mix = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];

/** Returns a canvas (W x W/2) with the colour map. */
export function makeEarthCanvas(W = 2048) {
  const H = W / 2;
  const mc = document.createElement('canvas'); mc.width = W; mc.height = H;
  const g = mc.getContext('2d', { willReadFrequently: true });
  g.fillStyle = '#000'; g.fillRect(0, 0, W, H);
  const trace = (poly, color) => {
    g.fillStyle = color; g.beginPath();
    poly.forEach(([lo, la], i) => { const x = (lo + 180) / 360 * W, y = (90 - la) / 180 * H; i ? g.lineTo(x, y) : g.moveTo(x, y); });
    g.closePath(); g.fill();
  };
  LAND.forEach((p) => trace(p, '#fff'));
  WATER.forEach((p) => trace(p, '#000'));
  const d = g.getImageData(0, 0, W, H).data;
  const raw = new Float32Array(W * H);
  for (let i = 0; i < raw.length; i++) raw[i] = d[i * 4] / 255;
  const mNear = boxBlur(boxBlur(raw, W, H, 4), W, H, 4);     // coastline shaping
  const mWide = boxBlur(boxBlur(raw, W, H, 16), W, H, 16);   // shelf / shallow-water glow

  const out = g.createImageData(W, H);
  const o = out.data;
  const deep = [10, 38, 74], shelf = [34, 118, 152], ice = [226, 232, 238];
  const forest = [52, 104, 54], grass = [118, 148, 72], desert = [196, 168, 106], rock = [122, 112, 100], tundra = [140, 150, 128];
  for (let y = 0; y < H; y++) {
    const lat = 90 - (y + 0.5) / H * 180, la = lat * Math.PI / 180, cl = Math.cos(la), sl = Math.sin(la);
    const alat = Math.abs(lat);
    for (let x = 0; x < W; x++) {
      const lo = ((x + 0.5) / W * 360 - 180) * Math.PI / 180;
      const px = cl * Math.cos(lo), py = sl, pz = -cl * Math.sin(lo);   // matches three SphereGeometry
      const i = y * W + x;
      const n1 = fbm(px * 3 + 11, py * 3, pz * 3, 3);
      const n2 = fbm(px * 10, py * 10 + 5, pz * 10, 3);
      const land = mNear[i] + (n2 - 0.5) * 0.34 + (n1 - 0.5) * 0.18 > 0.5;
      let c;
      if (land) {
        const arid = Math.exp(-(((alat - 25) / 10) ** 2)) * 0.95 + (n1 - 0.5) * 0.9 - 0.3;
        const humid = smooth(0.35, 0.65, n2 + (alat < 15 ? 0.2 : 0) - (alat > 50 ? 0.1 : 0));
        c = mix(grass, forest, humid);
        c = mix(c, desert, smooth(0.25, 0.5, arid));
        c = mix(c, tundra, smooth(52, 66, alat));
        c = mix(c, rock, smooth(0.62, 0.8, n2 * 0.7 + n1 * 0.5 - 0.1) * 0.8);
        c = mix(c, ice, Math.max(smooth(66, 74, alat + (n1 - 0.5) * 10), smooth(0.8, 0.92, n2 * n1 * 1.5) * smooth(35, 55, alat)));
      } else {
        const shallow = smooth(0.0, 0.5, mWide[i]);
        c = mix(deep, shelf, shallow * 0.85);
        c = mix(c, [18, 70, 112], (n1 - 0.5) * 0.5 + 0.25 - shallow * 0.2);
        c = mix(c, ice, smooth(76, 84, alat + (n2 - 0.5) * 8));   // Arctic pack ice
      }
      o[i * 4] = c[0]; o[i * 4 + 1] = c[1]; o[i * 4 + 2] = c[2]; o[i * 4 + 3] = 255;
    }
  }
  g.putImageData(out, 0, 0);
  return mc;
}
